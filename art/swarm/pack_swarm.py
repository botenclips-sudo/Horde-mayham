"""Packs rendered frames into one strip per kind (src/assets/swarm/<kind>.webp) and writes
src/swarmMeta.ts with each kind's span (R units) and cell size (px).
Run: python pack_swarm.py <render dir> <repo root>"""
import sys, os, json, importlib.util
from PIL import Image

D, ROOT = sys.argv[1], sys.argv[2]
FRAMES = [f'walk{i}' for i in range(6)] + ['attack']
OUTD = os.path.join(ROOT, 'src/assets/swarm')
os.makedirs(OUTD, exist_ok=True)
# Read KINDS from the build script without running Blender.
src = open(os.path.join(os.path.dirname(__file__), 'build_swarm.py')).read()
kinds_src = src[src.index('KINDS = {'):src.index('WALK = 6')]
meta = {}
for line in kinds_src.splitlines():
    line = line.strip()
    if line.startswith("'") and '(b_' in line:
        k = line.split("'")[1]
        nums = line.split('(')[1].rstrip('),').split(',')
        meta[k] = [float(nums[2]), int(nums[3])]
total = 0
for k, (span, cell) in meta.items():
    if not os.path.exists(os.path.join(D, k, 'attack.png')):
        print('missing', k); continue
    strip = Image.new('RGBA', (cell * len(FRAMES), cell))
    for i, f in enumerate(FRAMES):
        im = Image.open(os.path.join(D, k, f + '.png')).convert('RGBA')
        strip.paste(im, (i * cell, 0))
    p = os.path.join(OUTD, k + '.webp')
    strip.save(p, 'WEBP', quality=88, method=6, alpha_quality=90)
    total += os.path.getsize(p)
with open(os.path.join(ROOT, 'src/swarmMeta.ts'), 'w') as f:
    f.write('// Generated by art/swarm/pack_swarm.py: [span in R units, cell px] per kind.\n')
    f.write('export const SWARM_META: Record<string, [number, number]> = ' + json.dumps(meta) + ';\n')
    f.write(f'export const SWARM_FRAMES = {len(FRAMES)};\n')
print('total KB', total // 1024)
